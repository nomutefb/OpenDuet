// [결정] 보기에 「이미 대답함」 뜻이 이미 있으면 앱이 붙이는 「이미 대답함」 단추를 또 안 붙임
//   (형 11-20 03:41 dm-gik 「그리구 애들 질의가 객관식이 이미 대답함이 1개 더 생겨버리는데 그러지않게 확인해주라」 · 깃 [도움])
//   까닭 = 공지 「질문 → … 객관식 4문답 제공(3번 이미 응답, 4번 기타_주관식 입력 포함할 것)」대로 애들이 「③ 이미 응답」을 넣음 + 앱이 늘 붙이는 단추(형 11-13 09:12) = 둘
//   같은 뜻 = 「이미 대답 · 이미 응답 · 이미 답(함 · 했음 · 변)」 · 그 보기를 누르면 서버가 「✓ ③ 이미 응답」으로 묻는 이한테 줌(앱 단추와 같은 뜻)
export const HAD_RE = /이미\s*(?:대답|응답|답)/;
export const hasHad = (choices: readonly string[] | undefined) => (choices || []).some((c) => HAD_RE.test(String(c || "")));

// 형 글 속 별(*) = 글자 그대로 — 마크다운 굵게 · 기울임 · 가로줄(***)로 안 바뀜(형 11-20 11:04 dm-bom 봄 옮김 「그리고 내가 여기 채팅에 별을 쓸떼, 여러개쓰면 막 꼬여 정상적으로 그냥 쓸수잇게 조치좀, 여기서 굳이 내가 별을 써서 강조할 필요가없어」)
//   봇 글 꾸밈은 그대로(이 함수는 형 글에만) · 코드(``` · `) 안은 손 안 댐(거기선 별이 원래 글자)
export const starLit = (t: string): string => t.split(/(```[\s\S]*?```|`[^`\n]*`)/).map((x, i) => (i % 2 ? x : x.replace(/\\?\*/g, "\\*"))).join("");
